const SUPPORTED_LANGS = ['en', 'hi', 'mr'];

function getLang() {
  const saved = localStorage.getItem('dhaaga_lang');
  return SUPPORTED_LANGS.includes(saved) ? saved : 'en';
}

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = 'en';
  localStorage.setItem('dhaaga_lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.classList.toggle('lang-devanagari', lang === 'hi' || lang === 'mr');
  applyStaticTranslations();
  document.querySelectorAll('.lang-chip').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
}

function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}

function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  setLang(getLang());
  document.querySelectorAll('.lang-chip').forEach(btn => {
    btn.addEventListener('click', () => {
      setLang(btn.dataset.lang);
      if (typeof onLangChange === 'function') onLangChange();
    });
  });
});
